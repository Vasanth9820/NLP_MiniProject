"""
ai_detector.py
--------------
AI-generated text classification module.

Uses a scikit-learn pipeline:
  TfidfVectorizer  →  LogisticRegression

The trained model is loaded from  models/ai_detector.pkl  if it exists.
If the model file is not found, the module provides a clear message
explaining how to train it.
"""

from __future__ import annotations

import os
import pathlib
from typing import Optional

import joblib
import numpy as np

# Path resolution works regardless of the current working directory.
_ROOT = pathlib.Path(__file__).resolve().parents[1]
MODEL_PATH = _ROOT / "models" / "ai_detector.pkl"

# Labels the classifier uses
LABEL_AI = "ai"
LABEL_HUMAN = "human"

AI_DETECTION_DISCLAIMER = (
    "⚠️ **Disclaimer:** AI-generated text detection is probabilistic and may "
    "produce false positives or false negatives. This result should NOT be "
    "treated as definitive proof that text was or was not generated by AI. "
    "Always combine this result with human judgement."
)


class AIDetector:
    """
    Wrapper around a trained scikit-learn pipeline for AI-text classification.

    Usage
    -----
    detector = AIDetector()
    if detector.is_ready:
        result = detector.predict("Some text here...")
    """

    def __init__(self, model_path: str | pathlib.Path = MODEL_PATH) -> None:
        self.model_path = pathlib.Path(model_path)
        self.pipeline = None
        self.is_ready: bool = False
        self._load_model()

    def _load_model(self) -> None:
        """Attempt to load the trained pipeline from disk."""
        if not self.model_path.exists():
            self.is_ready = False
            return
        try:
            self.pipeline = joblib.load(self.model_path)
            self.is_ready = True
        except Exception:  # noqa: BLE001
            self.is_ready = False

    def predict(self, text: str) -> dict:
        """
        Classify a single piece of text.

        Parameters
        ----------
        text : str
            Input text to classify.

        Returns
        -------
        dict with keys:
          - prediction   : 'ai' | 'human' | 'uncertain'
          - confidence   : float  (0–100 %)
          - ai_prob      : float  (0–100 %)
          - human_prob   : float  (0–100 %)
          - label        : display string
          - model_ready  : bool
        """
        base_result = {
            "prediction": "uncertain",
            "confidence": 0.0,
            "ai_prob": 0.0,
            "human_prob": 0.0,
            "label": "Uncertain",
            "model_ready": self.is_ready,
        }

        if not self.is_ready:
            return base_result

        if not text or len(text.strip()) < 50:
            return {
                **base_result,
                "label": "Text too short for reliable prediction",
            }

        try:
            proba = self.pipeline.predict_proba([text])[0]
            classes = self.pipeline.classes_

            # Build a probability dict keyed by label
            prob_map = {cls: prob for cls, prob in zip(classes, proba)}
            ai_prob = prob_map.get(LABEL_AI, 0.0)
            human_prob = prob_map.get(LABEL_HUMAN, 0.0)

            # Determine prediction using a soft confidence threshold
            confidence = max(ai_prob, human_prob)
            if confidence < 0.55:
                prediction = "uncertain"
                label = "Uncertain"
            elif ai_prob > human_prob:
                prediction = LABEL_AI
                label = "Likely AI-generated"
            else:
                prediction = LABEL_HUMAN
                label = "Likely Human-written"

            return {
                "prediction": prediction,
                "confidence": round(confidence * 100, 1),
                "ai_prob": round(ai_prob * 100, 1),
                "human_prob": round(human_prob * 100, 1),
                "label": label,
                "model_ready": True,
            }

        except Exception as exc:  # noqa: BLE001
            return {
                **base_result,
                "label": f"Prediction error: {exc}",
            }

    def get_model_status_message(self) -> str:
        """Return a user-friendly message about model availability."""
        if self.is_ready:
            return f"✅ AI detector model loaded from `{self.model_path.name}`."
        return (
            "⚠️ No trained AI detector model found. "
            "To enable AI-content detection, follow these steps:\n\n"
            "1. Ensure `data/ai_text_dataset.csv` exists with columns `text` and `label`.\n"
            "2. Run the training script:\n"
            "   ```\n"
            "   python train_model.py\n"
            "   ```\n"
            "3. The model will be saved to `models/ai_detector.pkl`.\n"
            "4. Restart the application.\n\n"
            "A small demo dataset is included in `data/ai_text_dataset.csv` "
            "for testing, but a larger dataset is recommended for meaningful results."
        )


# Module-level singleton so app.py can do a simple import
_detector_instance: Optional[AIDetector] = None


def get_detector() -> AIDetector:
    """Return (or create) the module-level AIDetector singleton."""
    global _detector_instance
    if _detector_instance is None:
        _detector_instance = AIDetector()
    return _detector_instance

